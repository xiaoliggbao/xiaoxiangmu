#pragma once

// ============================================================
// common/Session.h
// 一条 TCP 连接的“登录状态”。
//
// 每个客户端连接都会创建一个 Session，只属于这个连接，
// 不共享，所以不需要加锁。
//
// 它记录：
//   - 有没有登录
//   - 登录的是哪个用户
//   - 这次登录的 token
//   - 当前在哪个房间
//   - 客户端注册的 RTP 端口（第五阶段用）
// ============================================================

#include <string>

struct Session {
    bool logged_in = false;   // 是否已经登录
    int user_id = 0;          // 登录后的用户 ID，例如 1001
    std::string username;     // 登录后的用户名
    std::string token;        // 服务器发给客户端的会话令牌
    int room_id = 0;          // 当前所在房间，0 表示不在房间
    int rtp_port = 0;         // 客户端注册的 RTP 接收端口
};
